// Prueba de humo con Electron real: escribe con eventos de teclado reales y comprueba el flujo.
const { app, BrowserWindow } = require('electron');
const path = require('path');
const fs = require('fs');
app.disableHardwareAcceleration();
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const out = [];
const ok = (c, m) => { out.push((c ? 'PASS ' : 'FAIL ') + m); };

const { ipcMain } = require('electron');
for (const [c, v] of [['app:initial-file', null], ['autosave:read', null], ['app:version', 'test']]) ipcMain.handle(c, () => v);
for (const c of ['app:set-dirty', 'app:state', 'app:set-theme']) ipcMain.on(c, () => {});
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1280, height: 860, show: true, webPreferences: { preload: path.join(__dirname, '..', 'preload.js'), contextIsolation: true, sandbox: true } });
  const errors = [];
  win.webContents.on('console-message', (_e, level, msg) => { if (level >= 2) errors.push(msg); });
  win.webContents.on('preload-error', (_e, p, err) => errors.push('preload: ' + err));
  await win.loadFile(path.join(__dirname, '..', 'src', 'index.html'));
  await sleep(600);
  const ev = (js) => win.webContents.executeJavaScript(js);
  const key = async (k, mods) => { win.webContents.sendInputEvent({ type: 'keyDown', keyCode: k, modifiers: mods || [] }); if (k.length === 1) win.webContents.sendInputEvent({ type: 'char', keyCode: k, modifiers: mods || [] }); win.webContents.sendInputEvent({ type: 'keyUp', keyCode: k, modifiers: mods || [] }); await sleep(12); };
  const type = async (s) => { for (const c of s) await key(c); };
  await ev("document.getElementById('script').focus()");
  await sleep(100);
  const blocks = () => ev("Array.from(document.querySelectorAll('#script .blk')).map(b=>b.dataset.type+':'+b.textContent)");

  await type('int. casa - dia'); await sleep(150);
  let b = await blocks();
  ok(b[0].startsWith('scene:'), 'escribir "int." convierte en escena -> ' + b[0]);
  await key('Return'); await type('Juan entra.'); await key('Tab'); await type('juan'); await key('Return'); await type('Hola.');
  await key('Return'); await sleep(150);
  b = await blocks();
  console.log(JSON.stringify(b));
  ok(b.map((x) => x.split(':')[0]).join(',') === 'scene,action,character,dialogue,action', 'flujo escena>acción>personaje>diálogo>acción = ' + b.map((x) => x.split(':')[0]).join(','));
  await key('Backspace'); await key('Backspace');
  b = await blocks();
  ok(b.length === 4, 'Backspace en bloque vacío lo elimina (' + b.length + ')');
  const status = await ev("document.getElementById('stPage').textContent + '|' + document.getElementById('stWords').textContent");
  ok(/Página 1 de 1/.test(status), 'barra de estado: ' + status);
  const mt = await ev("document.getElementById('meterTime').textContent");
  ok(mt !== '0:00', 'medidor de tiempo > 0: ' + mt);
  // autocompletado
  await key('Return'); await key('Return'); await sleep(50);
  await type('ext. '); await sleep(250);
  const acShown = await ev("!!document.querySelector('.ac')");
  ok(acShown, 'popup de autocompletado visible tras "ext. "');
  await key('Escape'); await type('calle'); await sleep(100);
  await type(' - '); await sleep(200);
  const times = await ev("Array.from(document.querySelectorAll('.ac-item')).map(e=>e.textContent).join(',')");
  ok(/DÍA/.test(times), 'sugiere momentos del día: ' + times);
  await key('Return'); await sleep(200);
  b = await blocks();
  ok(/^scene:ext\. calle - DÍA/i.test(b[b.length - 1]), 'acepta sugerencia con Enter: ' + b[b.length - 1]);
  const side = await ev("Array.from(document.querySelectorAll('#sideList .side-item')).map(e=>e.textContent).join(' | ')");
  ok(/INT\. CASA/i.test(side), 'navegador de escenas: ' + side);
  const before = (await blocks()).length;
  await key('z', ['control']); await sleep(900);
  const afterUndo = (await blocks()).length;
  ok(afterUndo <= before, 'deshacer cambia el documento (' + before + ' -> ' + afterUndo + ')');
  await key('y', ['control']); await sleep(900);
  ok((await blocks()).length >= afterUndo, 'rehacer');
  const html = await ev("G.exporter.buildHtml(document.getElementById('script') && (function(){return {meta:{title:'Prueba',credit:'Por',author:'Yo',source:'',date:'',contact:'',draft:''},blocks:Array.from(document.querySelectorAll('#script .blk')).map((e,i)=>({id:'x'+i,type:e.dataset.type,html:e.innerHTML})),settings:{lang:'es',formatId:'feature-letter',sceneNumbers:true,watermark:''}}})())");
  const tmp = path.join(require('os').tmpdir(), 'smoke.html'); fs.writeFileSync(tmp, html);
  const pw = new BrowserWindow({ show: true, width: 900, height: 1000, webPreferences: { sandbox: true, javascript: false } });
  await pw.loadFile(tmp); await sleep(500);
  fs.writeFileSync('/tmp/shot-print.png', (await pw.webContents.capturePage()).toPNG());
  const pdf = await pw.webContents.printToPDF({ preferCSSPageSize: true, printBackground: true });
  fs.writeFileSync('/tmp/smoke.pdf', pdf);
  ok(pdf.slice(0, 4).toString() === '%PDF', 'PDF generado: ' + pdf.length + ' bytes');
  pw.destroy();
  win.focus(); await sleep(600);
  fs.writeFileSync('/tmp/shot-light.png', (await win.webContents.capturePage()).toPNG());
  await ev("document.getElementById('btnTheme').click()"); await sleep(1200);
  fs.writeFileSync('/tmp/shot-dark.png', (await win.webContents.capturePage()).toPNG());
  ok(errors.length === 0, 'sin errores de consola: ' + errors.join(' | '));
  console.log(out.join('\n'));
  app.exit(out.some((l) => l.startsWith('FAIL')) ? 1 : 0);
});
